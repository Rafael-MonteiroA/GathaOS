"""Expand Gatha's original 5x7 drawings into fixed 8x16 bitmap cells.

All drawings are original project artwork, not imported font data.
This is a maintenance tool; normal builds use the checked-in font.h.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
glyphs = {c: list(map(int, rows.split(','))) for c, rows in
          re.findall(r"\['(.)'\]\s*=\s*\{([0-9,]+)\}", (root / 'kernel/panic_font.h').read_text())}
glyphs.update({
    ' ': [0,0,0,0,0,0,0], '!': [4,4,4,4,4,0,4],
    '"': [10,10,10,0,0,0,0], '#': [10,31,10,10,31,10,0],
    '$': [4,15,20,14,5,30,4], '%': [25,26,2,4,8,11,19],
    '&': [12,18,20,8,21,18,13], "'": [4,4,8,0,0,0,0],
    '(': [2,4,8,8,8,4,2], ')': [8,4,2,2,2,4,8],
    '*': [0,4,21,14,21,4,0], '+': [0,4,4,31,4,4,0],
    ',': [0,0,0,0,0,4,8], '.': [0,0,0,0,0,0,4],
    '/': [1,2,2,4,8,8,16], ';': [0,4,0,0,4,4,8],
    '<': [1,2,4,8,4,2,1], '>': [16,8,4,2,4,8,16],
    '@': [14,17,23,21,23,16,14], '[': [14,8,8,8,8,8,14],
    '\\': [16,8,8,4,2,2,1], ']': [14,2,2,2,2,2,14],
    '^': [4,10,17,0,0,0,0], '_': [0,0,0,0,0,0,31],
    '`': [8,4,2,0,0,0,0], '{': [3,4,4,8,4,4,3],
    '|': [4,4,4,4,4,4,4], '}': [24,4,4,2,4,4,24],
    '~': [0,0,9,22,0,0,0],
    'a': [0,0,14,1,15,17,15], 'b': [16,16,30,17,17,17,30],
    'c': [0,0,15,16,16,16,15], 'd': [1,1,15,17,17,17,15],
    'e': [0,0,14,17,31,16,14], 'f': [6,8,8,30,8,8,8],
    'g': [0,15,17,17,15,1,14], 'h': [16,16,30,17,17,17,17],
    'i': [4,0,12,4,4,4,14], 'j': [2,0,6,2,2,18,12],
    'k': [16,16,18,20,24,20,18], 'l': [12,4,4,4,4,4,14],
    'm': [0,0,26,21,21,21,21], 'n': [0,0,30,17,17,17,17],
    'o': [0,0,14,17,17,17,14], 'p': [0,30,17,17,30,16,16],
    'q': [0,15,17,17,15,1,1], 'r': [0,0,22,25,16,16,16],
    's': [0,0,15,16,14,1,30], 't': [8,8,30,8,8,9,6],
    'u': [0,0,17,17,17,19,13], 'v': [0,0,17,17,17,10,4],
    'w': [0,0,17,17,21,21,10], 'x': [0,0,17,10,4,10,17],
    'y': [0,17,17,17,15,1,14], 'z': [0,0,31,2,4,8,31],
})
lines = ['/* Original Gatha 8x16 font. See docs/graphics-font-license.txt. */',
         '#ifndef GATHA_FONT_H', '#define GATHA_FONT_H', '#include <stdint.h>',
         'static const uint8_t gatha_font[95][16] = {']
for code in range(32, 127):
    rows = glyphs[chr(code)]
    assert len(rows) == 7 and all(0 <= row < 32 for row in rows)
    bitmap = [0] + [row << 2 for row in rows for _ in range(2)] + [0]
    lines.append('    {' + ','.join(f'0x{row:02x}' for row in bitmap) + f'}}, /* ASCII {code} */')
lines += ['};', '#endif', '']
(root / 'gui/gfx/font.h').write_text('\n'.join(lines))
